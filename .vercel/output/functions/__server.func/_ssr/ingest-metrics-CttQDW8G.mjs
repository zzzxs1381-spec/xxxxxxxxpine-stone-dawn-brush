function classify(evidence) {
	const by = (name) => evidence.find((e) => e.check === name);
	if (by("online")?.result === "offline") return "OFFLINE";
	if (by("https")?.result === "captive") return "CAPTIVE_PORTAL_OR_PROXY";
	if (by("dns")?.result === "fail") return "DNS_FAILURE";
	const tcp = evidence.filter((e) => e.check.startsWith("tcp:"));
	const tcpFail = tcp.length > 0 && tcp.every((e) => e.result === "fail");
	const tcpOk = tcp.some((e) => e.result === "ok");
	if (tcpFail) return "IP_UNREACHABLE";
	if (by("tls")?.result === "fail" && tcpOk) return "TLS_HANDSHAKE_INTERFERENCE";
	if (evidence.some((e) => e.check.startsWith("tls-sni:") && e.result === "fail") && (tcpOk || by("https")?.result === "ok" || by("origin-rtt")?.result === "ok")) return "TLS_HANDSHAKE_INTERFERENCE";
	if (by("https")?.result === "fail" && (by("same-origin")?.result === "ok" || tcpOk)) return "TLS_HANDSHAKE_INTERFERENCE";
	if (by("https")?.result === "fail" && tcp.length === 0 && by("origin-rtt")?.result === "fail") return "IP_UNREACHABLE";
	if (tcp.length >= 2 && tcp.some((e) => e.result === "fail") && tcpOk) return "TCP_PORT_FILTERING";
	if (by("udp-dns")?.result === "fail") return "UDP_UNAVAILABLE";
	if (by("udp-hint")?.result === "fail") return "UDP_UNAVAILABLE";
	const latencies = evidence.filter((e) => (e.check === "https" || e.check === "tls" || e.check === "origin-rtt") && e.result === "ok" && typeof e.ms === "number").map((e) => e.ms);
	if (latencies.length > 0 && Math.min(...latencies) > 1200) return "HIGH_LATENCY";
	if (evidence.some((e) => e.result === "fail" && e.check !== "ipv6" && e.check !== "udp-hint")) return "UNKNOWN";
	return "NO_BLOCK_DETECTED";
}
